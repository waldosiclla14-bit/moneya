-- ---------------------------------------------------------------------------
-- Tablas de referencia (lectura para usuarios autenticados; escritura solo
-- vía service_role: sin policies de escritura).
-- ---------------------------------------------------------------------------
create table public.countries (
    id            smallint generated by default as identity primary key,
    code          text unique not null check (code in ('CL', 'PE')),
    name          text not null,
    currency_code text not null,
    locale        text not null
);

-- Regla 5 del PRD: la tabla `indicators` solo acepta las 4 métricas de Global
-- Findex 2025 en V1. Cualquier indicador nuevo requiere migración + ficha en
-- `indicator_sources`.
create type public.indicator_key as enum (
    'account_ownership',      -- % adultos con cuenta financiera (account.t.d / FX.OWN.TOTL.ZS)
    'saved_formally_last_year', -- % que ahorró formalmente en el último año (fin17a.17a1.d)
    'formal_credit_access',   -- % con acceso a crédito formal (fin22a.22a1.22g.d)
    'emergency_funds'         -- % que podría acceder a dinero extra en una emergencia (fin44)
);

create table public.indicator_sources (
    id           uuid primary key default gen_random_uuid(),
    source_key   text unique not null,
    name         text not null,
    institution  text not null,
    edition      text not null,
    data_year    smallint not null,
    methodology  text not null,
    url          text not null,
    accessed_at  date not null default current_date,
    notes        text
);

create table public.indicators (
    id            uuid primary key default gen_random_uuid(),
    indicator_key public.indicator_key not null,
    country_id    smallint not null references public.countries (id),
    source_id     uuid not null references public.indicator_sources (id),
    value         numeric(5,2) check (value between 0 and 100),
    unit          text not null default '%',
    year          smallint not null,
    fnd_code      text,
    unique (indicator_key, country_id, source_id)
);

create table public.missions (
    id               uuid primary key default gen_random_uuid(),
    slug             text unique not null,
    title            text not null,
    description      text not null,
    sort_order       smallint not null,
    required_actions jsonb not null default '[]'::jsonb
);

create table public.lessons (
    id              uuid primary key default gen_random_uuid(),
    slug            text unique not null,
    title           text not null,
    summary         text not null,
    body            text not null,
    topic           public.lesson_topic not null,
    reading_minutes smallint not null default 3 check (reading_minutes > 0),
    published       boolean not null default false,
