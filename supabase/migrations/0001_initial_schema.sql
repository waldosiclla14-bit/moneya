-- Snapshot mensual. Corrección PRD: requiere saldo de liquidez (para "meses de
-- cobertura") e ingreso desglosado por fuente (para "concentración de ingreso").
create table public.financial_inputs (
    id                   uuid primary key default gen_random_uuid(),
    user_id              uuid not null references auth.users (id) on delete cascade,
    snapshot_month       date not null,
    income_dependiente   numeric(14,2) not null default 0 check (income_dependiente >= 0),
    income_independiente numeric(14,2) not null default 0 check (income_independiente >= 0),
    income_otros         numeric(14,2) not null default 0 check (income_otros >= 0),
    expenses_essential   numeric(14,2) not null default 0 check (expenses_essential >= 0),
    expenses_nonessential numeric(14,2) not null default 0 check (expenses_nonessential >= 0),
    liquid_balance       numeric(14,2) not null default 0 check (liquid_balance >= 0),
    created_at           timestamptz not null default now(),
    updated_at           timestamptz not null default now(),
    unique (user_id, snapshot_month),
    check (snapshot_month = (date_trunc('month', snapshot_month))::date)
);

create table public.liabilities (
    id             uuid primary key default gen_random_uuid(),
    user_id        uuid not null references auth.users (id) on delete cascade,
    name           text not null,
    type           public.liability_type not null,
    balance        numeric(14,2) not null check (balance >= 0),
    monthly_payment numeric(14,2) not null check (monthly_payment >= 0),
    annual_rate    numeric(6,2) not null default 0 check (annual_rate >= 0),
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now()
);

-- Respuestas crudas del cuestionario CFPB adaptado. Regla de validez: la escala
-- requiere que TODOS los ítems estén respondidos y que no se altere la redacción.
create table public.wellbeing_answers (
    id                 uuid primary key default gen_random_uuid(),
    user_id            uuid not null references auth.users (id) on delete cascade,
    answered_at        timestamptz not null default now(),
    items              jsonb not null,
    all_items_answered boolean not null default false,
    check (jsonb_typeof(items) = 'array')
);

-- Score ÚNICO validado CFPB (0–100, método IRT) + desglose DESCRIPTIVO de las
-- 4 dimensiones de la escala. Las dimensiones NO son scores psicométricos.
create table public.wellbeing_results (
    id                 uuid primary key default gen_random_uuid(),
    user_id            uuid not null references auth.users (id) on delete cascade,
    answers_id         uuid not null references public.wellbeing_answers (id) on delete cascade,
    score              smallint not null check (score between 0 and 100),
    dimension_control  smallint not null check (dimension_control between 0 and 100),
    dimension_shock    smallint not null check (dimension_shock between 0 and 100),
    dimension_goals    smallint not null check (dimension_goals between 0 and 100),
    dimension_freedom  smallint not null check (dimension_freedom between 0 and 100),
    note               text not null default 'Desglose descriptivo derivado de los ítems CFPB; no constituye un score psicométrico por dimensión.',
    created_at         timestamptz not null default now(),
    unique (answers_id)
);

