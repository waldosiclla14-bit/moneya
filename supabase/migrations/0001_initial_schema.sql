create type public.liability_type as enum ('tarjeta', 'prestamo', 'hipoteca', 'vehiculo', 'otro');
create type public.scenario_type as enum ('ingresos_menos', 'gastos_mas', 'perdida_ingreso', 'emergencia', 'personalizado');
