-- Auditoría (security definer: el usuario no puede insertar logs falsos).
create or replace function public.audit_financial_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    acting_user uuid := auth.uid();
    record_id  uuid;
    snapshot   jsonb;
begin
    -- Sin contexto de usuario autenticado no se registra log (evita user_id inválidos).
    if acting_user is null then
        return coalesce(new, old);
    end if;
    record_id := coalesce(new.id, old.id);
    if tg_op = 'DELETE' then
        snapshot := to_jsonb(old);
    else
        snapshot := to_jsonb(new);
    end if;
    insert into public.audit_logs (user_id, table_name, record_id, action, data)
    values (acting_user, tg_table_name, record_id, tg_op::text, snapshot);
    return coalesce(new, old);
end;
$$;

create trigger trg_financial_inputs_audit
    after insert or update or delete on public.financial_inputs
    for each row execute function public.audit_financial_change();
create trigger trg_liabilities_audit
    after insert or update or delete on public.liabilities
    for each row execute function public.audit_financial_change();
create trigger trg_simulations_audit
    after insert or update or delete on public.simulations
    for each row execute function public.audit_financial_change();

